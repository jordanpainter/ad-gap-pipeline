md("""\
## Step 7: classify each gap's audio (PANNs)

Each gap goes into silence, music, sfx or ambient, using AudioSet's
ontology. Gaps shorter than Cnn14's minimum input (about 1 s) are padded
with neighbouring audio. The padding is reported, and a fifth bucket,
speech, shows when it pulled in narration.
""")

code("""\
gap_classifications = []
for g in gaps:
    result_cls = audio_classify.classify_gap(VIDEO_PATH, g.start, g.end, duration)
    gap_classifications.append(result_cls)
    print(f"gap [{g.start:.2f}-{g.end:.2f}]  dur={g.duration:.2f}s  pos={g.position}")
    print(f"  classified over [{result_cls.classify_start:.2f}-{result_cls.classify_end:.2f}]"
          f"  (padded {result_cls.padded_seconds:.2f}s)")
    print(f"  -> bucket={result_cls.bucket}  top={result_cls.top_label} ({result_cls.top_prob:.2f})")
    for lbl, p in result_cls.top5:
        print(f"     {lbl}: {p:.3f}")
    print()
""")

code("""\
n_speech_leak = sum(1 for c in gap_classifications if c.bucket == "speech")
n_padded = sum(1 for c in gap_classifications if c.padded_seconds > 0)
if n_speech_leak:
    print(f"{n_speech_leak}/{len(gaps)} gap(s) classified as 'speech': padding pulled in "
          f"adjacent narration. Expected for very short gaps.")
elif n_padded:
    print(f"{n_padded}/{len(gaps)} gap(s) needed padding but none leaked into 'speech'.")
else:
    print("All gaps were long enough to classify without padding.")
""")

md("""\
## Step 8: describe each gap's clip (Qwen3-VL)

Qwen3-VL gets the gap as a multi-frame clip and returns four fields, based
on what AD guidelines agree should be described: **subject** (worded like
the corpus's `referent_note` field), **action**, **scene** continuity and
on-screen **text**, plus a short free **description**. There's no minimum
gap length, since the model always gets a few frames. This step is
exploratory; the gap statistics don't depend on it.

### Choosing the model

`Qwen3-VL-8B-Instruct-4bit` described one hard clip, a 60 s fast-cutting
gap with no speech (the whole video is one gap), as "a static promotional
image... a central hourglass". The frames show a montage of sea creatures.
All 8 Qwen3-VL variants (2B, 4B, 8B and 30B-A3B, each as Instruct and
Thinking) were run on that clip, and the three strongest again on three
ordinary videos (a golden retriever, two bat clips) with hand-coded labels
to check against.

Every model handled the ordinary videos; the failures (hallucination,
reasoning loops, ignoring the output format) only showed up on the hard
clip. `Qwen3-VL-4B-Instruct-4bit` was the only model right on all four
videos, and also the smallest and fastest, so it's the default.
`8B-Instruct` hallucinates on hard content with no sign that it has.
`8B-Thinking` loops unless `repetition_penalty` is set, so it isn't safe to
run unattended; `describe_gap(..., repetition_penalty=1.3)` is there for
rerunning one gap whose description looks wrong. `30B-A3B` wasn't worth its
size. Four videos is a small test, and the ranking could change at scale.
""")

code("""\
gap_descriptions = []
for g in gaps:
    desc = frame_describe.describe_gap(VIDEO_PATH, g.start, g.end)
    gap_descriptions.append(desc)
    print(f"gap [{g.start:.2f}-{g.end:.2f}]  ({desc.sampled_frame_count} frames sampled "
          f"by the model, out of {desc.clip_total_frames} in the clip)")
    print(f"  subject: {desc.subject}")
    print(f"  action:  {desc.action}")
    print(f"  scene:   {desc.scene}")
    print(f"  text:    {desc.on_screen_text}")
    print(f"  description: {desc.description}\\n")

# Save this video's descriptions to data/descriptions/<video_id>.json.
saved_to = frame_describe.save_descriptions(VIDEO_ID, gaps, gap_descriptions)
print(f"saved -> {saved_to}")
""")

code("""\
# up to 3 representative frames per gap
n_show = 3
fig, axes = plt.subplots(len(gap_descriptions), n_show, figsize=(3.5 * n_show, 3.2 * len(gap_descriptions)))
axes = np.atleast_2d(axes).reshape(len(gap_descriptions), n_show)

for row, desc in enumerate(gap_descriptions):
    cap = cv2.VideoCapture(str(desc.clip_path))
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    idxs = np.linspace(0, max(total - 1, 0), n_show).round().astype(int)
    for col, idx in enumerate(idxs):
        cap.set(cv2.CAP_PROP_POS_FRAMES, int(idx))
        ret, frame = cap.read()
        ax = axes[row, col]
        if ret:
            ax.imshow(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
        ax.set_title(f"gap [{desc.clip_start:.1f}-{desc.clip_end:.1f}]  frame {col+1}/{n_show}", fontsize=8)
        ax.axis("off")
    cap.release()

fig.tight_layout()
plt.show()
""")

md("## Step 9: motion and cuts (a model-free check on Qwen3-VL's action and scene fields)")

